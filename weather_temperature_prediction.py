import pandas as pd
import numpy as np
df=pd.read_csv('weather.csv')
df

"""DATA UNDERSTANDING"""

df.head()

df.tail()

df.info()

df.describe()

df.columns

df.shape

df.sample(10)

"""CHECKING MISSING VALUES,DATATYPES AND DUPLICATES

"""

df.isna().sum()

df.dtypes

df["Description"].unique()

df=pd.get_dummies(df,columns=["Description"],dtype=int)

df.dtypes

df.drop_duplicates(inplace=True)

print("Zero pressure values:",(df["Pressure_millibars"]==0).sum())

df["Pressure_millibars"]=df["Pressure_millibars"].replace(0,np.nan)

df["Pressure_millibars"]=df["Pressure_millibars"].fillna(df["Pressure_millibars"].median())

"""FEATURES AND TARGET SELECTION"""

x=df.drop("Temperature_c",axis=1)
x

y=df["Temperature_c"]
y

"""DATA SPLITTING INTO TRAINING AND TESTING SETS"""

from sklearn.model_selection import train_test_split
x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.3,random_state=1)

"""FEATURES SCALING"""

from sklearn.preprocessing import MinMaxScaler
scaler=MinMaxScaler()
x_train_scaled=scaler.fit_transform(x_train)
x_test_scaled=scaler.fit_transform(x_test)

"""DATA SIZE CHECKING"""

x_train.shape,x_test.shape

y_train.shape,y_test.shape

"""MODEL SELECTION"""

from sklearn.linear_model import LinearRegression
lr=LinearRegression()
lr.fit(x_train_scaled,y_train)

y_pred=lr.predict(x_test_scaled)
y_pred

y_test.values

from sklearn.neighbors import KNeighborsRegressor
knn=KNeighborsRegressor(n_neighbors=5)
knn.fit(x_train_scaled,y_train)

y_pred1=knn.predict(x_test_scaled)
y_pred1

from sklearn.svm import SVR
svr=SVR()
svr.fit(x_train_scaled,y_train)

y_pred2=svr.predict(x_test_scaled)
y_pred2

"""PERFORMANCE EVALUATION"""

from sklearn.metrics import r2_score,mean_absolute_error,mean_squared_error,root_mean_squared_error
models={"Linear regression":y_pred,"KNN":y_pred1,"SVR":y_pred2}
for name,predictions in models.items():
  print("Model:",name)
  print("r2_score:",r2_score(y_test,predictions)*100)
  print("mean_absolute_error:",mean_absolute_error(y_test,predictions))
  print("mean_squared_error:",mean_squared_error(y_test,predictions))
  print("root_mean_squared_error:",root_mean_squared_error(y_test,predictions))

